//! Platform-neutral storage for the small set of application secrets.
//!
//! Callers choose one of the closed slots below and only receive the byte
//! storage operations they need. Serialization and credential validation stay
//! with the feature that owns the credential.

use std::{fmt, sync::Arc};

use serde::{Deserialize, Serialize};

#[cfg(target_os = "macos")]
mod macos;

/// The application-owned Keychain items.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum SecretSlot {
    ApiOpenAi,
    ApiAnthropic,
    ApiGemini,
    ApiOpenAiCompatible,
}

/// The managed credential formats supported by the application boundary.
///
/// The variants are deliberately closed. Provider-specific parsing belongs to
/// the owner of the credential, while this module only selects its storage
/// namespace.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub enum ManagedSecretKind {
    ApiKey,
    LicenseKey,
}

impl ManagedSecretKind {
    pub(crate) const fn keychain_label(self) -> &'static str {
        match self {
            Self::ApiKey => "api-key",
            Self::LicenseKey => "license-key",
        }
    }
}

/// Opaque managed-secret identifier suitable for storing in configuration.
///
/// References contain no provider name, Keychain service, filesystem path, or
/// secret material. Lowercase hexadecimal is used so parsing is stable across
/// TOML, IPC, and platform adapters.
#[derive(Clone, PartialEq, Eq, Hash, Serialize)]
#[serde(transparent)]
pub struct ManagedSecretRef(Box<str>);

impl ManagedSecretRef {
    pub const LENGTH: usize = 32;

    pub fn parse(value: &str) -> Result<Self, SecretStoreError> {
        if value.len() != Self::LENGTH
            || value
                .bytes()
                .any(|byte| !matches!(byte, b'0'..=b'9' | b'a'..=b'f'))
        {
            return Err(SecretStoreError::InvalidReference);
        }
        Ok(Self(value.to_owned().into_boxed_str()))
    }

    pub(crate) fn from_uuid(value: uuid::Uuid) -> Self {
        Self(value.simple().to_string().into_boxed_str())
    }

    pub(crate) fn as_str(&self) -> &str {
        &self.0
    }
}

impl fmt::Debug for ManagedSecretRef {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        formatter
            .debug_tuple("ManagedSecretRef")
            .field(&self.0)
            .finish()
    }
}

impl<'de> Deserialize<'de> for ManagedSecretRef {
    fn deserialize<D>(deserializer: D) -> Result<Self, D::Error>
    where
        D: serde::Deserializer<'de>,
    {
        let value = String::deserialize(deserializer)?;
        Self::parse(&value).map_err(serde::de::Error::custom)
    }
}

impl fmt::Display for ManagedSecretRef {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        formatter.write_str(&self.0)
    }
}

/// Build namespace used to keep development credentials separate from the
/// packaged application.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub enum ManagedSecretNamespace {
    Development,
    Release,
}

impl ManagedSecretNamespace {
    pub(crate) const fn keychain_label(self) -> &'static str {
        match self {
            Self::Development => "dev",
            Self::Release => "release",
        }
    }

    pub const fn current() -> Self {
        if cfg!(debug_assertions) {
            Self::Development
        } else {
            Self::Release
        }
    }
}

/// Per-installation scope for managed credentials.
///
/// The identity is generated by `managed_credentials` and persisted beside
/// the app-owned config file. It is never read from TOML.
#[derive(Clone, PartialEq, Eq)]
pub struct ManagedSecretScope {
    namespace: ManagedSecretNamespace,
    installation_id: Box<str>,
}

impl ManagedSecretScope {
    pub(crate) fn new(namespace: ManagedSecretNamespace, installation_id: String) -> Self {
        Self {
            namespace,
            installation_id: installation_id.into_boxed_str(),
        }
    }

    pub(crate) fn namespace(&self) -> ManagedSecretNamespace {
        self.namespace
    }

    pub(crate) fn installation_id(&self) -> &str {
        &self.installation_id
    }
}

#[derive(Clone, Copy, PartialEq, Eq)]
pub enum SecretStoreError {
    UnsupportedPlatform,
    Backend,
    Locked,
    InvalidReference,
    /// The owning feature rejected the bytes as an invalid credential.
    /// The raw store never performs this validation.
    Corrupt,
}

impl fmt::Debug for SecretStoreError {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        fmt::Display::fmt(self, formatter)
    }
}

impl fmt::Display for SecretStoreError {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        let message = match self {
            Self::UnsupportedPlatform => "secret storage is unsupported on this platform",
            Self::Backend => "secret storage backend failed",
            Self::Locked => "secret storage is locked",
            Self::InvalidReference => "managed secret reference is invalid",
            Self::Corrupt => "stored secret is invalid",
        };
        formatter.write_str(message)
    }
}

impl std::error::Error for SecretStoreError {}

/// Raw byte storage for one fixed application secret slot.
pub trait SecretStore: Send + Sync + 'static {
    fn get(&self) -> Result<Option<Vec<u8>>, SecretStoreError>;
    fn set(&self, secret: &[u8]) -> Result<(), SecretStoreError>;
    fn delete(&self) -> Result<(), SecretStoreError>;
}

/// Construct the platform implementation for a known application slot.
pub fn secret_store(slot: SecretSlot) -> Result<Arc<dyn SecretStore>, SecretStoreError> {
    #[cfg(target_os = "macos")]
    {
        macos::store(slot)
    }

    #[cfg(not(target_os = "macos"))]
    {
        let _ = slot;
        Err(SecretStoreError::UnsupportedPlatform)
    }
}

/// Construct a raw byte store for one app-owned managed credential item.
///
/// The returned interface is the same one used by the fixed development probe
/// slots. The scope, kind, and opaque reference are resolved by the platform
/// adapter and cannot select an arbitrary service or path.
pub(crate) fn managed_secret_store(
    scope: ManagedSecretScope,
    kind: ManagedSecretKind,
    reference: ManagedSecretRef,
) -> Result<Arc<dyn SecretStore>, SecretStoreError> {
    #[cfg(target_os = "macos")]
    {
        macos::managed_store(scope, kind, reference)
    }

    #[cfg(not(target_os = "macos"))]
    {
        let _ = scope;
        let _ = kind;
        let _ = reference;
        Err(SecretStoreError::UnsupportedPlatform)
    }
}
